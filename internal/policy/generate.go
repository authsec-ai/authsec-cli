// Generated is a policy with the reasons behind its entries, for Render.
type Generated struct {
	Policy *Policy
	Header []string          // comment lines at the top
	Notes  map[string]string // "network.allow[2]" -> "llm, seen 14 times"
}

// GenInput is what a policy is generated from.
type GenInput struct {
	AgentID, AgentName string
	Activity           *access.Summary // nil: not seen running (defaults only)
	MCPConfigured      []string        // MCP server names in the agent's configuration
	Home               string          // the agent user's home, written as {home}
	Since              time.Time       // start of the activity window
	Now                time.Time
	Version            string // CLI version, for the header
	// IsRepo reports whether a directory is a project root (has .git);
	// injected for tests.
	IsRepo func(dir string) bool
}

// DefaultDeniedPaths are credential stores no agent policy allows unless a
// person moves them.
var DefaultDeniedPaths = []string{
	"{home}/.ssh", "{home}/.aws", "{home}/.kube", "{home}/.azure", "{home}/.config/gcloud",
	"{home}/.docker/config.json", "{home}/.netrc", "{home}/.git-credentials", "{home}/.gnupg",
	"{home}/.password-store", "{home}/.vault-token", "{home}/.config/gh/hosts.yml",
}

// DefaultDeniedCommands are destructive commands; DefaultAskCommands change
// infrastructure and need a person. They are matched per simple command
// after wrappers (sudo, env, sh -c) are looked through, ignoring case; rm is
// matched as "rm -rf TARGET" whatever the flag spelling, and git without its
// global options. '\*' is a literal star (rm -rf /\* is "rm -rf /*" typed).
var (
	DefaultDeniedCommands = append([]string{
		"rm -rf /", "rm -rf /\\*", "rm -rf ~", "rm -rf ~/", "rm -rf ~/\\*", "rm -rf $HOME", "rm -rf $HOME/", "rm -rf $HOME/\\*",
		"rm -rf /home", "rm -rf /etc", "rm -rf /usr", "rm -rf /var",
		"sudo *", "doas *", "su", "su *", "mkfs*", "dd *of=/dev/*", "chmod -R 777 *",
		"git push --force*", "git push *--force*", "git push -f", "git push -f *", "git push * -f", "git push * -f *", "git push * +*",
		"git reset --hard*", "git clean -*f*",
		"kubectl delete namespace*", "kubectl delete ns*", "kubectl * delete namespace*", "kubectl * delete ns*",
		"terraform destroy*", "terraform * destroy*", "helm uninstall*", "helm delete*",
		"curl *|*sh", "curl *|*sh *", "curl *|*bash", "curl *|*bash *", "curl *|*zsh",
		"wget *|*sh", "wget *|*sh *", "wget *|*bash", "wget *|*bash *",
	}, sqlDenies()...)
	DefaultAskCommands = []string{
		"terraform apply*", "terraform * apply*", "kubectl apply*", "kubectl * apply*", "kubectl delete*", "kubectl * delete*",
		"helm upgrade*", "helm install*", "aws * delete*", "aws * terminate*", "az * delete*", "gcloud * delete*",
		"docker push*", "npm publish*", "git push*",
		// Programs that start work outside the agent's process tree, where
		// its network and command rules do not reach.
		"systemd-run*", "systemctl --user*", "docker run*", "docker exec*", "podman run*", "podman exec*",
		"tmux*", "screen*", "at *", "crontab*", "nsenter*",
	}
)

// sqlDenies are destructive SQL through the usual database clients (a grep
// for "DROP TABLE" in migrations is not one).
func sqlDenies() []string {
	var out []string
	for _, c := range []string{"psql", "mysql", "mariadb", "sqlite3", "sqlcmd", "clickhouse-client", "cockroach"} {
		out = append(out, c+" *drop table*", c+" *drop database*", c+" *truncate *")
	}
	return out
}

// OwnCredentials are an agent's own login files. A generated policy keeps
// them readable: denying them logs the agent out.
var OwnCredentials = map[string][]string{
	"claude-code": {"{home}/.claude/.credentials.json"},
	"codex":       {"{home}/.codex/auth.json"},
	"gemini-cli":  {"{home}/.gemini/oauth_creds.json"},
}

// Generate builds a policy from what an agent was seen doing: it allows the
// destinations and paths it used, denies credential stores and destructive
// commands, and starts in monitor mode.
func Generate(in GenInput) *Generated {
	if in.IsRepo == nil {
		in.IsRepo = func(dir string) bool {
			st, err := os.Stat(filepath.Join(dir, ".git"))
			return err == nil && st.IsDir()
		}
	}
	g := &Generated{Notes: map[string]string{}, Policy: &Policy{
		APIVersion: APIVersion, Kind: Kind, Mode: Monitor,
		Agent:      AgentRef{ID: in.AgentID, Name: in.AgentName},
		Network:    Network{Default: Deny},
		Commands:   Commands{Default: Allow},
		MCPServers: MCPServers{Default: Deny},
	}}
	p := g.Policy
	a := in.Activity
	skipped := 0

	g.Header = []string{
		fmt.Sprintf("Policy for %s, generated by authsec-cli %s on %s.", nameOr(in.AgentName, in.AgentID), in.Version, in.Now.Format("2006-01-02")),
	}
	if a != nil {
		g.Header = append(g.Header, fmt.Sprintf("From activity %s to %s: %d destinations, %d files, %d programs.",
			a.FirstSeen.Local().Format("Jan 2 15:04"), a.LastSeen.Local().Format("Jan 2 15:04"), len(a.Destinations), len(a.Files), len(a.Commands)))
	} else {
		g.Header = append(g.Header, "Not seen running: defaults only. Run 'sudo authsec-cli daemon' for a while and generate again.")
	}
	g.Header = append(g.Header,
		"mode: monitor logs what would be blocked; change it to enforce to block.",
		"Edit freely, then run: authsec-cli policy check")

	// Network: what it used, plus the model API it needs.
	seen := map[string]int{} // rule -> index in allow
	addRule := func(r Rule, note string) {
		key := r.Host + "|" + r.CIDR + "|" + fmt.Sprint(r.Port)
		if i, ok := seen[key]; ok {
			field := fmt.Sprintf("network.allow[%d]", i)
			g.Notes[field] += "; " + note
			return
		}
		seen[key] = len(p.Network.Allow)
		g.Notes[fmt.Sprintf("network.allow[%d]", len(p.Network.Allow))] = note
		p.Network.Allow = append(p.Network.Allow, r)
	}
	for _, h := range ModelHosts[in.AgentID] {
		addRule(Rule{Host: h, Port: 443}, "model API")
	}
	if a != nil {
		for _, d := range a.Destinations {
			r := Rule{Host: strings.TrimSuffix(strings.ToLower(d.Host), "."), Port: d.Port}
			note := fmt.Sprintf("%s, seen %s", d.Category, times(d.Count))
			if r.Host != "" && !validHost(r.Host) {
				if d.Host != "ollama (local)" {
					note += ", host " + strconv.Quote(d.Host) + " is not a valid name"
				}
				r.Host = ""
			}
			if r.Host == "" {
				r.CIDR = hostCIDR(d.IP)
			}
			if r.Host == "" && r.CIDR == "" {
				skipped++
				continue
			}
			addRule(r, note)
		}
	}

	// Files: the directories it wrote and read, collapsed to project roots
	// and top-level directories; credential stores denied.
	if a != nil {
		var writes, reads []string
		sensitive := map[string]int{}
		own := map[string]bool{}
		for _, c := range OwnCredentials[in.AgentID] {
			own[filepath.Clean(strings.ReplaceAll(c, "{home}", in.Home))] = true
		}
		for _, f := range a.Files {
			switch {
			case !safeText(f.Path) || !filepath.IsAbs(f.Path):
				skipped++
			case own[filepath.Clean(f.Path)]:
				reads = append(reads, f.Path) // its own login: stays readable
			case f.Sensitive:
				sensitive[f.Path] += f.Count
			case f.Access == "write":
				writes = append(writes, f.Path)
			default:
				reads = append(reads, f.Path)
			}
		}
		rw := anchors(writes, in.Home, in.IsRepo)
		ro := anchors(reads, in.Home, in.IsRepo)
		if len(rw.projects) > 0 || len(ro.projects) > 0 {
			list, key := &p.Filesystem.ReadOnly, "read_only"
			projects := append(append([]string(nil), rw.projects...), ro.projects...)
			if len(rw.projects) > 0 {
				list, key = &p.Filesystem.ReadWrite, "read_write"
			}
			var shown []string
			for _, d := range dedupe(sortedCopy(projects)) {
				shown = append(shown, tildeVar(d, in.Home))
			}
			g.Notes[fmt.Sprintf("filesystem.%s[%d]", key, len(*list))] = "the project it works in; seen: " + strings.Join(shown, ", ")
			*list = append(*list, "{project}")
		}
		for _, d := range rw.dirs {
			g.Notes[fmt.Sprintf("filesystem.read_write[%d]", len(p.Filesystem.ReadWrite))] = rw.note[d]
			p.Filesystem.ReadWrite = append(p.Filesystem.ReadWrite, tildeVar(d, in.Home))
		}
		for _, d := range ro.dirs {
			if coveredBy(d, rw.dirs) {
				continue
			}
			g.Notes[fmt.Sprintf("filesystem.read_only[%d]", len(p.Filesystem.ReadOnly))] = ro.note[d]
			p.Filesystem.ReadOnly = append(p.Filesystem.ReadOnly, tildeVar(d, in.Home))
		}
		for _, d := range DefaultDeniedPaths {
			note := "credential store"
			full := strings.ReplaceAll(d, "{home}", in.Home)
			n := 0
			for path, c := range sensitive {
				if under(path, full) {
					n += c
					delete(sensitive, path)
				}
			}
			if n > 0 {
				note = fmt.Sprintf("credential store; the agent read it %s: denying may break that, move it to read_only to allow", times(n))
			}
			g.Notes[fmt.Sprintf("filesystem.deny[%d]", len(p.Filesystem.Deny))] = note
			p.Filesystem.Deny = append(p.Filesystem.Deny, d)
		}
		var rest []string
		for path := range sensitive {
			rest = append(rest, path)
		}
		sort.Strings(rest)
		for _, path := range rest {
			g.Notes[fmt.Sprintf("filesystem.deny[%d]", len(p.Filesystem.Deny))] = fmt.Sprintf("credential file the agent opened %s", times(sensitive[path]))
			p.Filesystem.Deny = append(p.Filesystem.Deny, tildeVar(path, in.Home))
		}
	} else {
		for i, d := range DefaultDeniedPaths {
			g.Notes[fmt.Sprintf("filesystem.deny[%d]", i)] = "credential store"
			p.Filesystem.Deny = append(p.Filesystem.Deny, d)
		}
	}

	// Commands: destructive ones denied, infrastructure changes need a
	// person; what it ran is listed for the reader.
	p.Commands.Deny = append([]string(nil), DefaultDeniedCommands...)
	p.Commands.Ask = append([]string(nil), DefaultAskCommands...)
	if a != nil && len(a.Commands) > 0 {
		var ran []string
		for i, c := range a.Commands {
			if i == 12 {
				ran = append(ran, fmt.Sprintf("+%d more", len(a.Commands)-12))
				break
			}
			ran = append(ran, fmt.Sprintf("%s ×%d", c.Program, c.Count))
		}
		g.Notes["commands"] = "programs it ran: " + strings.Join(ran, ", ")
	}

	// MCP servers: the ones it is configured with.
	mcp := append([]string(nil), in.MCPConfigured...)
	sort.Strings(mcp)
	for _, m := range dedupe(mcp) {
		if !safeText(m) || strings.TrimSpace(m) == "" {
			skipped++
			continue
		}
		g.Notes[fmt.Sprintf("mcp_servers.allow[%d]", len(p.MCPServers.Allow))] = "configured"
		p.MCPServers.Allow = append(p.MCPServers.Allow, m)
	}
	if skipped > 0 {
		g.Header = append(g.Header, fmt.Sprintf("%d observed names were left out: not valid host names, paths or MCP server names.", skipped))
	}
	return g
}

// DefaultPolicy is the policy for agents without their own (unknown agents
// included): monitor, credential stores and destructive commands denied,
// network open.
func DefaultPolicy(version string, now time.Time) *Generated {
	g := Generate(GenInput{AgentID: AnyAgent, AgentName: "every agent without its own policy", Now: now, Version: version})
	g.Policy.Network.Default = Allow
	g.Policy.MCPServers.Default = Allow
	g.Header = []string{
		fmt.Sprintf("Default policy, generated by authsec-cli %s on %s.", version, now.Format("2006-01-02")),
		"Applies to agents that have no policy file of their own, unknown agents included.",
		"mode: monitor logs what would be blocked; change it to enforce to block.",
		"Edit freely, then run: authsec-cli policy check",
	}
	return g
}

type anchored struct {
	dirs     []string // directories (and single files) to name
	projects []string // project (git) roots, written as {project}
	note     map[string]string
}

// anchors collapses file paths to what a policy should name: {project} for
// files in a git project, a tool's own directory (~/.claude,
// ~/.config/gh), a file's directory outside projects, or a top-level system
// directory (/tmp, /etc, /var/lib/x). Never /, a home directory or a
// directory every tool shares (~/.config, ~/.local/share).
func anchors(paths []string, home string, isRepo func(string) bool) anchored {
	count := map[string]int{}
	example := map[string]string{}
	projects := map[string]bool{}
	for _, p := range paths {
		a, project := anchor(p, home, isRepo)
		switch {
		case project:
			projects[a] = true
		case a != "":
			count[a]++
			if example[a] == "" {
				example[a] = p
			}
		}
	}
	var dirs []string
	for d := range count {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	var out []string
	for _, d := range dirs {
		if !coveredBy(d, out) {
			out = append(out, d)
		}
	}
	notes := map[string]string{}
	for _, d := range out {
		n := 0
		for k, c := range count {
			if under(k, d) {
				n += c
			}
		}
		notes[d] = fmt.Sprintf("%d %s, e.g. %s", n, plural(n, "file", "files"), strconv.Quote(tildeVar(example[d], home)))
	}
	var projs []string
	for d := range projects {
		projs = append(projs, d)
	}
	sort.Strings(projs)
	return anchored{dirs: out, projects: projs, note: notes}
}

// sharedDirs hold many tools' files, credentials included: a policy names
// the tool's own directory below them, never them.
var sharedDirs = []string{".config", ".local/share", ".local/state", ".local/lib", ".local/bin", ".cache",
	"Library/Application Support", "Library/Caches", "Library/Preferences", "AppData/Roaming", "AppData/Local", "AppData/LocalLow"}

// homeOfPath returns the home directory a path is in: the agent user's, or
// any /home/<user>, /Users/<user> or /root.
func homeOfPath(path, home string) string {
	if home != "" && under(path, home) {
		return home
	}
	parts := strings.Split(strings.Trim(path, "/"), "/")
	switch {
	case len(parts) >= 2 && (parts[0] == "home" || parts[0] == "Users"):
		return "/" + parts[0] + "/" + parts[1]
	case len(parts) >= 1 && parts[0] == "root":
		return "/root"
	}
	return ""
}

// anchor returns what to name for one path, and whether it is a project root.
func anchor(path, home string, isRepo func(string) bool) (string, bool) {
	path = filepath.Clean(path)
	h := homeOfPath(path, home)
	if path == "/" || (h != "" && (path == h || under(h, path))) || path == "/home" || path == "/Users" {
		return "", false // never / or a home directory (or a parent of it) as a whole
	}
	dir := filepath.Dir(path)
	if h != "" {
		rel := strings.TrimPrefix(path, h+"/")
		for _, sd := range sharedDirs {
			if rel == sd || under(rel, sd) {
				inner := strings.Split(strings.TrimPrefix(strings.TrimPrefix(rel, sd), "/"), "/")
				if len(inner) <= 1 || strings.HasSuffix(sd, "bin") {
					return path, false // a file directly in a shared directory: name it alone
				}
				return filepath.Join(h, sd, inner[0]), false
			}
		}
		first := strings.Split(rel, "/")[0]
		if !strings.Contains(rel, "/") {
			return path, false // a file directly in home
		}
		if strings.HasPrefix(first, ".") {
			return filepath.Join(h, first), false // a tool's own directory: ~/.claude, ~/.codex
		}
		for d := dir; d != h && under(d, h); d = filepath.Dir(d) {
			if isRepo(d) {
				return d, true
			}
		}
		return dir, false // outside a project: the file's directory
	}
	for d := dir; d != "/" && d != "." && strings.HasPrefix(d, "/"); d = filepath.Dir(d) {
		if isRepo(d) {
			return d, true
		}
	}
	parts := strings.Split(strings.Trim(path, "/"), "/")
	switch {
	case len(parts) <= 1:
		return path, false
	case parts[0] == "var" || parts[0] == "opt" || parts[0] == "srv":
		if len(parts) >= 3 {
			return "/" + filepath.Join(parts[0], parts[1], parts[2]), false
		}
		return "/" + filepath.Join(parts[0], parts[1]), false
	default:
		return "/" + parts[0], false
	}
}

// safeText reports whether a name or path can go into a policy file: valid
// UTF-8 without control characters.
func safeText(s string) bool {
	if !utf8.ValidString(s) {
		return false
	}
	for _, r := range s {
		if unicode.IsControl(r) || r == '\u2028' || r == '\u2029' || r == '\u0085' {
			return false
		}
	}
	return true
}

func sortedCopy(xs []string) []string {
	out := append([]string(nil), xs...)
	sort.Strings(out)
	return out
}

func coveredBy(d string, dirs []string) bool {
	for _, o := range dirs {
		if under(d, o) {
			return true
		}
	}
	return false
}

func tildeVar(p, home string) string {
	if home != "" && under(p, home) {
		return "{home}" + strings.TrimPrefix(p, home)
	}
	return p
}

func hostCIDR(ip string) string {
	parsed := net.ParseIP(ip)
	if parsed == nil {
		return ""
	}
	if parsed.To4() != nil {
		return parsed.String() + "/32"
	}
	return parsed.String() + "/128"
}

func times(n int) string {
	if n == 1 {
		return "once"
	}
	return fmt.Sprintf("%d times", n)
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

func nameOr(name, id string) string {
	if name != "" {
		return name
	}
	return id
}

func dedupe(xs []string) []string {
	var out []string
	for i, x := range xs {
		if i == 0 || x != xs[i-1] {
			out = append(out, x)
		}
	}
	return out
}
